CREATE TABLE dish (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    name varchar(50) NOT NULL,
    role varchar(20) NOT NULL,
    cuisine varchar(10) NOT NULL,
    main_ingredients varchar(100) NOT NULL,
    methods varchar(100) NOT NULL,
    flags varchar(100) NOT NULL,
    dessert_type varchar(10),
    image_group varchar(10),
    heavy_soup boolean NOT NULL,
    serving_gram integer NOT NULL,
    calorie numeric(7,1) NOT NULL,
    protein numeric(6,1) NOT NULL,
    fat numeric(6,1) NOT NULL,
    carbohydrate numeric(6,1) NOT NULL,
    source varchar(30) NOT NULL,
    frequency integer NOT NULL,
    pairings varchar(200) NOT NULL,
    ingredients varchar(300) NOT NULL,
    seasonings varchar(200) NOT NULL,
    CONSTRAINT dish_pkey PRIMARY KEY (id),
    CONSTRAINT uk_dish_role_name UNIQUE (role, name)
);
