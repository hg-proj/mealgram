DROP TABLE member_saved_meal;
DROP TABLE recipe_ingredient;
DROP TABLE recipe;

CREATE TABLE member_saved_meal (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    member_id bigint NOT NULL,
    meal_id varchar(36) NOT NULL,
    candidate_index integer NOT NULL,
    style varchar(50) NOT NULL,
    reason varchar(300) NOT NULL,
    dishes_json text NOT NULL,
    nutrition_json text NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT member_saved_meal_pkey PRIMARY KEY (id),
    CONSTRAINT uk_member_saved_meal_candidate UNIQUE (member_id, meal_id, candidate_index),
    CONSTRAINT fk_member_saved_meal_member FOREIGN KEY (member_id) REFERENCES member(id) ON DELETE CASCADE
);
